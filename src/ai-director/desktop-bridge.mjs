// A04: exact existing Studio read-only IPC + proposed native guarded interface.
// Does NOT route AI actions to unguarded video_timeline_apply/motion_command.
// Host must register ai_director_* in the reviewed unified Tauri build.
import {validateSnapshot,sameSnapshot,validateAction} from "./contracts.mjs";

const SHA = /^[a-f0-9]{64}$/;
const SESSION = /^[A-Za-z0-9][A-Za-z0-9_-]{7,127}$/;
const SAFE = /^[A-Za-z0-9][A-Za-z0-9_-]{7,63}$/;
const READY = "ai_director_capabilities";
const GUARDED = "ai_director_execute_guarded";
function object(x,label) {
  if (!x || typeof x !== "object" || Array.isArray(x) ||
    Object.getPrototypeOf(x) !== Object.prototype) throw new Error(label+" must be an object");
  return x;
}
function trustedBinding(x) {
  object(x,"native owner binding");
  const keys=x.engine==="video" ? ["engine","sessionId","selectedRoot","projectPath"] :
    x.engine==="motion" ? ["engine","sessionId","projectId"] : [];
  if (!keys.length || Object.keys(x).length!==keys.length ||
    keys.some(k=>!Object.hasOwn(x,k))) throw new Error("unexpected native owner binding fields");
  if (typeof x.sessionId!=="string" || !SESSION.test(x.sessionId))
    throw new Error("trusted owner session nonce required");
  const id=x.engine==="video" ? x.projectPath : x.projectId;
  if (typeof id!=="string" || !id || id.length>1024 || /[\u0000-\u001f]/.test(id))
    throw new Error("native project identity required");
  if (x.engine==="video" &&
    (typeof x.selectedRoot!=="string" || !x.selectedRoot || x.selectedRoot.length>1024))
    throw new Error("trusted owner-selected project root required");
  return Object.freeze({...x});
}
function invokeSafe(invoke,command,args) {
  // Real Tauri invoke only; missing command fails closed, no simulated success.
  return invoke(command,args);
}
export function createStudioReadback({invoke,ownerBinding}={}) {
  if (typeof invoke!=="function" || typeof ownerBinding!=="function")
    throw new Error("trusted Tauri invoke and owner binding ports required");
  async function readSnapshot() {
    const before=trustedBinding(await ownerBinding());
    let response;
    if(before.engine==="video") {
      response=object(await invokeSafe(invoke,"video_project_snapshot",
        {selectedRoot:before.selectedRoot,projectPath:before.projectPath}),"FilmCraft native snapshot");
      if(response.projectPath!==before.projectPath || !SHA.test(response.projectSha256) ||
         !Number.isSafeInteger(response.sessionRevision) || response.sessionRevision<0 ||
         !response.project || typeof response.project!=="object")
        throw new Error("FilmCraft native project/SHA readback invalid");
    } else {
      response=object(await invokeSafe(invoke,"motion_command",
        {request:{action:"status"}}),"EffectCraft native status");
      if(response.ready!==true || response.native!==true ||
        response.engine!=="effectcraft" ||
        !Number.isSafeInteger(response.projectRevision) || response.projectRevision<0)
        throw new Error("EffectCraft native owner not ready");
    }
    // Host binding nonce MUST be generated by the native owner on open/restart;
    // these existing Studio commands do not yet provide it themselves.
    const after=trustedBinding(await ownerBinding());
    if(JSON.stringify(before)!==JSON.stringify(after))
      throw new Error("OWNER_CHANGED_DURING_READBACK");
    return validateSnapshot({
      engine:before.engine,
      projectId:before.engine==="video"?before.projectPath:before.projectId,
      sessionId:before.sessionId,
      version:before.engine==="video"?response.projectSha256:response.projectRevision
    });
  }
  return Object.freeze({readSnapshot});
}
function validateCapabilities(c) {
  object(c,"native AI host capabilities");
  if(c.nativeGuarded!==true || c.sameOwnerAsManual!==true ||
    c.ownerConsent!==true || c.durableIdempotency!==true ||
    c.independentObjectReadback!==true || c.version!==1)
    throw new Error("NATIVE_AI_GUARD_NOT_READY");
  return true;
}
export function createGuardedDesktopAdapter({invoke,readback}={}) {
  if(typeof invoke!=="function" || typeof readback?.readSnapshot!=="function")
    throw new Error("trusted guarded desktop ports required");
  async function requireReady() {
    const caps=await invokeSafe(invoke,READY,{});
    return validateCapabilities(caps);
  }
  async function executeGuarded(request) {
    object(request,"guarded action request");
    const exact=["action","expectedSnapshot","idempotencyKey","taskId","stepIndex"];
    if(Object.keys(request).length!==exact.length ||
      exact.some(k=>!Object.hasOwn(request,k)))
      throw new Error("invalid native guarded request");
    const expected=validateSnapshot(request.expectedSnapshot);
    const action=validateAction(request.action,expected.engine);
    if(!SHA.test(request.idempotencyKey)||!SAFE.test(request.taskId)||
       !Number.isSafeInteger(request.stepIndex)||request.stepIndex<0||request.stepIndex>11)
      throw new Error("invalid native task binding");
    await requireReady();
    const observed=validateSnapshot(await readback.readSnapshot());
    if(!sameSnapshot(expected,observed))throw new Error("STALE_PROJECT_BEFORE_GUARD");
    // Only this new command may execute. The native owner must atomically
    // verify actual approval/plan/version/step intent before any mutation.
    const receipt=object(await invokeSafe(invoke,GUARDED,{
      request:{taskId:request.taskId,stepIndex:request.stepIndex,
        idempotencyKey:request.idempotencyKey,expectedSnapshot:expected,action}
    }),"native guarded receipt");
    const actual=validateSnapshot(receipt.after);
    if(receipt.guarded!==true || receipt.nativeVerified!==true ||
      receipt.idempotencyKey!==request.idempotencyKey ||
      typeof receipt.objectProofSha256!=="string" || !SHA.test(receipt.objectProofSha256) ||
      receipt.taskId!==request.taskId || receipt.stepIndex!==request.stepIndex)
      throw new Error("NATIVE_GUARDED_RECEIPT_INVALID");
    return {guarded:true,nativeVerified:true,idempotencyKey:request.idempotencyKey,
      after:actual};
  }
  return Object.freeze({readSnapshot:()=>readback.readSnapshot(),requireReady,executeGuarded});
}
export const aiDesktopCommands=Object.freeze({
  capabilities:READY,executeGuarded:GUARDED,
  videoSnapshot:"video_project_snapshot",motion:"motion_command"
});
